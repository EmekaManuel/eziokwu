// Regenerates shared/src/abi.ts from the compiled BountyBoard (run `forge build` in /contracts first).
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const abi = execSync("forge inspect BountyBoard abi --json", { cwd: "contracts" }).toString();
writeFileSync(
  "shared/src/abi.ts",
  `// GENERATED by scripts/gen-abi.mjs from contracts/src/BountyBoard.sol. Do not edit.\nexport const bountyBoardAbi = ${abi.trim()} as const;\n`,
);
console.log("wrote shared/src/abi.ts");
